// Bundle the server recorder (pure core + Postgres store + thin handlers) into
// one platform-neutral ES module for the Supabase Edge Functions.
// Output is generated (gitignored): supabase/functions/_shared/recorder-core.js
import { build } from "esbuild";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../..", import.meta.url));
const outfile = process.argv[2] ?? `${root}supabase/functions/_shared/recorder-core.js`;

const result = await build({
  entryPoints: [`${root}src/server/recorder/entry.ts`],
  bundle: true,
  format: "esm",
  platform: "neutral",
  target: "es2022",
  mainFields: ["module", "main"],
  alias: { "@": `${root}src` },
  outfile,
  metafile: true,
  legalComments: "none",
  banner: { js: "// GENERATED by scripts/recorder/bundle.mjs — do not edit." },
});
const out = Object.values(result.metafile.outputs)[0];
const external = out.imports.filter((i) => i.external).map((i) => i.path);
if (external.length) {
  console.error(`bundle has external imports: ${external.join(", ")}`);
  process.exit(1);
}
console.log(
  `${outfile} ${(out.bytes / 1024).toFixed(1)} KB, ${Object.keys(out.inputs).length} inputs, 0 external imports`,
);
